/**
 * 이 인스턴스가 데모인지 판별한다.
 *
 * 데모는 실제 주문·결제가 아닌데도 겉모습이 진짜와 같다. 표시가 없으면
 * 테스트 주문이 진짜 주문으로 오해되고, 검색엔진에 잡히면 가짜 상품 페이지가
 * 브랜드 검색 결과로 노출된다 — 그래서 배너와 색인 차단을 한 스위치로 묶는다.
 *
 * **서버에서만 읽는다.** 클라이언트 번들에서 `process.env`는 빌드 시점에
 * 박제되므로(값이 없으면 영원히 undefined), 서버 컴포넌트·라우트 핸들러에서만 쓴다.
 */

/** 켜는 값은 "1" 하나로 못 박는다 — "false"·"0"이 참으로 새는 흔한 사고를 막는다 */
export function isDemoDeployment(): boolean {
  return process.env.PARASOL_DEMO_MODE === "1";
}
